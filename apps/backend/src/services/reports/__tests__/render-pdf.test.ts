
import { describe, it, expect } from "vitest";
import { ZodError } from "zod";
import {
  renderPdf,
  parseInlineBold,
  parseBlocks,
  PdfRenderError,
} from "../render-pdf";
import { renderPdfInputSchema, MAX_TABLE_ROWS } from "../schema";
import type { RenderPdfInput } from "../schema";

const GOLDEN_FIXTURE: RenderPdfInput = {
  title: "Smoke Test Q1",
  filename: "smoke-test.pdf",
  sections: [
    {
      heading: "Revenue Snapshot",
      body_markdown:
        "This is **Q1 results** with a few sentences. Plain prose with one **bold** highlight.",
      table: {
        columns: ["Region", "Rev"],
        rows: [
          ["North", "$100k"],
          ["South", "$80k"],
        ],
      },
    },
    {
      heading: "Observations",
      body_markdown:
        "Three things stood out:\n\n- north grew faster\n- south plateaued\n- east is new territory",
    },
  ],
  footer: "Generated by Praxis",
};

describe("render-pdf — happy path", () => {
  it("renders a golden small fixture and produces a PDF in the expected length range", async () => {
    const bytes = await renderPdf(GOLDEN_FIXTURE);
    const head = Buffer.from(bytes.subarray(0, 5)).toString();
    expect(head).toBe("%PDF-");
    expect(bytes.byteLength).toBeGreaterThan(1500);
    expect(bytes.byteLength).toBeLessThan(20_000);
  });

  it("does not stamp the Zavi product wordmark on the page (S7)", async () => {
    const { default: pdfParse } = await import("pdf-parse");
    const bytes = await renderPdf(GOLDEN_FIXTURE);
    const { text } = await pdfParse(Buffer.from(bytes));
    expect(text).not.toMatch(/ZAVI/i);
  });

  it("rejects oversized prose at the schema layer", () => {
    const oversized: RenderPdfInput = {
      title: "X",
      filename: "x.pdf",
      sections: [
        { heading: "Big", body_markdown: "a".repeat(51_000) },
      ],
    };
    expect(() => renderPdfInputSchema.parse(oversized)).toThrow(ZodError);
  });

  it("rejects empty sections at the schema layer", () => {
    expect(() =>
      renderPdfInputSchema.parse({
        title: "X",
        filename: "x.pdf",
        sections: [],
      } as unknown as RenderPdfInput),
    ).toThrow(ZodError);
  });

  it("rejects jagged tables at the schema layer", () => {
    expect(() =>
      renderPdfInputSchema.parse({
        title: "X",
        filename: "x.pdf",
        sections: [
          {
            heading: "S",
            body_markdown: "",
            table: {
              columns: ["A", "B", "C"],
              rows: [["1", "2"]],
            },
          },
        ],
      } as unknown as RenderPdfInput),
    ).toThrow(ZodError);
  });

  it("rejects > MAX_TABLE_ROWS rows at the schema layer", () => {
    const rows = Array(MAX_TABLE_ROWS + 1).fill(["a", "b"]);
    expect(() =>
      renderPdfInputSchema.parse({
        title: "X",
        filename: "x.pdf",
        sections: [
          {
            heading: "S",
            body_markdown: "",
            table: { columns: ["A", "B"], rows },
          },
        ],
      } as unknown as RenderPdfInput),
    ).toThrow(ZodError);
  });
});

describe("render-pdf — preformatted wireframe block", () => {
  const WIREFRAME = [
    "┌──────────────────────────┐",
    "│  Header        [ Login ] │",
    "├──────────────────────────┤",
    "│  Hero copy               │",
    "│   [  Get started  ]      │",
    "└──────────────────────────┘",
  ].join("\n");

  it("accepts a section.preformatted field at the schema layer", () => {
    const input: RenderPdfInput = {
      title: "Wireframe",
      filename: "wf.pdf",
      sections: [{ heading: "Landing", body_markdown: "Proposed layout:", preformatted: WIREFRAME }],
    };
    const parsed = renderPdfInputSchema.parse(input);
    expect(parsed.sections[0].preformatted).toBe(WIREFRAME);
  });

  it("renders a wireframe to a valid PDF (magic bytes + plausible size)", async () => {
    const bytes = await renderPdf({
      title: "Wireframe",
      filename: "wf.pdf",
      sections: [{ heading: "Landing", body_markdown: "Proposed layout:", preformatted: WIREFRAME }],
    });
    expect(Buffer.from(bytes.subarray(0, 5)).toString()).toBe("%PDF-");
    expect(bytes.byteLength).toBeGreaterThan(1500);
  });

  it("preserves whitespace lines — a preformatted block adds bytes vs the same section without it", async () => {
    const base: RenderPdfInput = {
      title: "WF",
      filename: "wf.pdf",
      sections: [{ heading: "Screen", body_markdown: "desc" }],
    };
    const withPre: RenderPdfInput = {
      title: "WF",
      filename: "wf.pdf",
      sections: [
        {
          heading: "Screen",
          body_markdown: "desc",
          preformatted: "    indented line\n\n        deeper indent\n+--------+\n| box    |\n+--------+",
        },
      ],
    };
    const a = await renderPdf(base);
    const b = await renderPdf(withPre);
    expect(b.byteLength).toBeGreaterThan(a.byteLength);
  });

  it("counts preformatted against the total prose budget (oversized rejected)", () => {
    expect(() =>
      renderPdfInputSchema.parse({
        title: "X",
        filename: "x.pdf",
        sections: Array.from({ length: 6 }, (_, i) => ({
          heading: `S${i}`,
          body_markdown: "",
          preformatted: "x".repeat(11_900),
        })),
      } as unknown as RenderPdfInput),
    ).toThrow(ZodError);
  });

  it("rejects a single oversized preformatted block at the field cap", () => {
    expect(() =>
      renderPdfInputSchema.parse({
        title: "X",
        filename: "x.pdf",
        sections: [{ heading: "S", body_markdown: "", preformatted: "x".repeat(12_001) }],
      } as unknown as RenderPdfInput),
    ).toThrow(ZodError);
  });
});

