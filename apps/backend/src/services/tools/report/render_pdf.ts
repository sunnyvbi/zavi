export const renderPdfTool: ToolSpec<RenderPdfInput, DeliverPdfResult> = {
  name: "report_render_pdf",
  effect: "write",
  description: DESCRIPTION,
  input_schema: renderPdfInputSchemaCoerced,
  async execute(ctx, input) {
    if (!ctx.run_id) {
      throw new ExpectedToolError(
        "missing_run_ctx",
        "report.render_pdf requires an active run_id in context.",
      );
    }
    return deliverPdf(
      {
        tenant_id: ctx.tenant_id,
        run_id: ctx.run_id,
        slack_team_id: ctx.slack_team_id,
        log: ctx.log,
      },
      input,
    );
  },
};
