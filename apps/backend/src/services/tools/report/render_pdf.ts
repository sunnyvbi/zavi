  "this call returns an error (below), do NOT claim a file exists — report the",
  "render failed.",
  "Errors: invalid_input, missing_run_ctx, filename_invalid, run_lookup_failed,",
  "tenant_mismatch, pdf_render_failed, pdf_render_timeout, pdf_too_large,",
  "storage_upload_failed, artifact_row_failed.",
