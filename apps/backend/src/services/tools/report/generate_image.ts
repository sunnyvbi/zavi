export const generateImageTool: ToolSpec<GenerateImageInput, DeliverImageResult> = {
  name: "report_generate_image",
  effect: "write",
  description: DESCRIPTION,
  input_schema: generateImageInputSchema,
  async execute(ctx, input) {
    if (!ctx.run_id) {
      throw new ExpectedToolError(
        "missing_run_ctx",
        "report.generate_image requires an active run_id in context.",
      );
    }
    return deliverImage(
      {
        tenant_id: ctx.tenant_id,
        run_id: ctx.run_id,
        slack_team_id: ctx.slack_team_id,
        log: ctx.log,
      },
      input,
    );
  },
};
