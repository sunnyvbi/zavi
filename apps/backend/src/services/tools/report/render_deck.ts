  "    the viewer presses N; NEVER printed in the PDF.",
  "",
  "DATA: every number, quote and claim on a slide must come from something you",
  "actually retrieved this run. Do not invent metrics to fill a `metrics` slide —",
  "an empty deck is recoverable, a confidently wrong one presented to a board is",
  "not. If you do not have the number, write the slide without it.",
  "",
  "THE LINK IS PUBLIC, AND YOU MUST SAY SO. Unlike `render_wireframe` (which",
  "requires invented placeholder data), a deck is expected to carry the",
  "operator's REAL figures — and the `url` is an UNAUTHENTICATED page: the",
  "address is unguessable and expires in 30 days, but anyone who obtains it can",
  "read the deck without signing in. That is deliberate — a deck is made to be",
  "forwarded — which is exactly why the operator has to be told. Say it plainly",
