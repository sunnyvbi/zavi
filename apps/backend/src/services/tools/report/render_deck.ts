
import type { ToolSpec, ToolContext } from "@/services/tools/types";
import { ExpectedToolError } from "@/services/tools/types";
import { renderDeckInputSchema, MAX_SLIDES, DECK_PROSE_BUDGET } from "@/services/reports/deck-schema";
import type { RenderDeckInput } from "@/services/reports/deck-schema";
import { deliverDeck, type DeliverDeckResult } from "@/services/reports/deliver-deck";

