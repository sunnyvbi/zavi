  "Build a real SLIDE DECK and deliver it two ways: a shareable link the",
  "operator can open and forward (an interactive HTML deck — arrow keys, click,",
  "presenter notes, print-to-PDF) AND a landscape 16:9 PDF file attached to your",
  "reply. Use this whenever someone asks for a deck, slides, a presentation, a",
  "pitch/board/QBR/kickoff deck, or 'something I can present'.",
  "",
  "Pick the right tool:",
  "  - a DECK (slides someone presents or forwards) → this tool.",
  "  - a REPORT / document / memo (prose, tables, an evidence packet) →",
  "    `render_pdf`. Do NOT fake a deck by putting one 'slide' per render_pdf",
  "    section — that produces a portrait document, not a deck.",
  "  - a clickable UI PROTOTYPE / wireframe of a screen → `render_wireframe`.",
  "",
  "YOU WRITE THE CONTENT, NOT THE DESIGN. Send structured slides; the server",
