export const renderDeckTool: ToolSpec<RenderDeckInput, DeliverDeckResult> = {
  name: "report_render_deck",
  effect: "write",
  description: DESCRIPTION,
  input_schema: renderDeckInputSchema,
  async execute(ctx: ToolContext, input: RenderDeckInput) {
    if (!ctx.run_id) {
      throw new ExpectedToolError(
        "missing_run_ctx",
        "report.render_deck requires an active run_id in context.",
      );
    }
    return deliverDeck(
      {
        tenant_id: ctx.tenant_id,
        run_id: ctx.run_id,
        slack_team_id: ctx.slack_team_id,
        log: ctx.log,
      },
      input,
    );
  },
};
