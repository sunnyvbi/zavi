
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const HERE = __dirname;
const FILES_DIR = join(HERE, "files");
const VARIANTS_DIR = join(HERE, "variants");
const OUT = join(HERE, "template-files.generated.ts");

export function collectTemplateFiles(root: string = FILES_DIR): Array<{ path: string; content: string }> {
  const out: Array<{ path: string; content: string }> = [];
  const walk = (dir: string): void => {
    for (const name of readdirSync(dir).sort()) {
      const abs = join(dir, name);
      const st = statSync(abs);
      if (st.isDirectory()) {
        walk(abs);
      } else if (st.isFile()) {
        const rel = relative(root, abs).split(sep).join("/");
        out.push({ path: rel, content: readFileSync(abs, "utf-8") });
      }
    }
  };
  walk(root);
  return out;
}

export function collectVariantFiles(
  root: string = VARIANTS_DIR,
): Record<string, Array<{ path: string; content: string }>> {
  const out: Record<string, Array<{ path: string; content: string }>> = {};
  for (const name of readdirSync(root).sort()) {
    const abs = join(root, name);
    if (statSync(abs).isDirectory()) out[name] = collectTemplateFiles(abs);
  }
  return out;
}

export function renderModule(
  files: Array<{ path: string; content: string }>,
  variants: Record<string, Array<{ path: string; content: string }>> = {},
): string {
  const header = `// @generated by generate-template-files.ts — DO NOT EDIT BY HAND.
// Edit the source files under ./files/ and re-run the generator. The drift test
// (template-files.test.ts) fails if this file is stale.
//
// Build-safe embedding of the nextjs-supabase-tailwind starter app: a map of
// repo-relative path -> UTF-8 content, seeded onto each provisioned company repo.

export const TEMPLATE_FILES: Readonly<Record<string, string>> = Object.freeze({
`;
  const body = files
    .map(({ path, content }) => `  ${JSON.stringify(path)}: ${JSON.stringify(content)},`)
    .join("\n");
  const variantBody = Object.entries(variants)
    .map(
      ([name, vfiles]) =>
        `  ${JSON.stringify(name)}: Object.freeze({\n` +
        vfiles.map(({ path, content }) => `    ${JSON.stringify(path)}: ${JSON.stringify(content)},`).join("\n") +
        `\n  }),`,
    )
    .join("\n");
  const footer = `
});

export const TEMPLATE_FILE_PATHS: readonly string[] = Object.freeze(Object.keys(TEMPLATE_FILES));

// Per-category package.json + package-lock.json pairs from ./variants/<name>/.
export const TEMPLATE_VARIANTS: Readonly<Record<string, Readonly<Record<string, string>>>> = Object.freeze({
${variantBody}
});
`;
  return header + body + footer;
}

function main(): void {
  const files = collectTemplateFiles();
  const module = renderModule(files, collectVariantFiles());
  writeFileSync(OUT, module, "utf-8");
  // eslint-disable-next-line no-console
  console.log(`wrote ${OUT} (${files.length} files)`);
}

if (require.main === module) {
  main();
}
