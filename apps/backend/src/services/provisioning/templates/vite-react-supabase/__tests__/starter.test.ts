describe("vite-react-supabase starter: dependencies", () => {
  const pkg = JSON.parse(TEMPLATE_FILES["package.json"]);

  it("every dependency is exact-pinned", () => {
    const bad = Object.entries({ ...pkg.dependencies, ...pkg.devDependencies })
      .filter(([, v]) => !EXACT.test(String(v)))
      .map(([k, v]) => `${k}@${v}`);
    expect(bad).toEqual([]);
  });

  it("has dev, build, typecheck and smoke scripts", () => {
    expect(pkg.scripts.dev).toContain("vite");
    expect(pkg.scripts.build).toContain("vite build");
    expect(pkg.scripts.typecheck).toContain("tsc");
    expect(pkg.scripts.smoke).toBe(`node ${SMOKE_SCRIPT_PATH}`);
    expect(pkg.dependencies["@supabase/supabase-js"]).toBeDefined();
    expect(pkg.dependencies["react-router-dom"]).toBeDefined();
    expect(pkg.devDependencies.playwright).toBeDefined();
  });

  it.skipIf(!HAS_LOCK)(
    "package-lock.json satisfies package.json (skipped while files/package-lock.json is absent: run scripts/generate-vite-starter-lockfile.ts in e2b to create it)",
    () => {
      const lock = JSON.parse(TEMPLATE_FILES["package-lock.json"]);
      const root = lock.packages[""];
      const rootSpecs = { ...root.dependencies, ...root.devDependencies };
      for (const [name, spec] of Object.entries({ ...pkg.dependencies, ...pkg.devDependencies })) {
        expect(rootSpecs[name], `${name} missing from lock root`).toBe(spec);
        expect(lock.packages[`node_modules/${name}`]?.version, `${name} unresolved in lock`).toBe(spec);
      }
    },
  );
});

describe("vite-react-supabase starter: secrets", () => {
  it("no VITE_ variable name mentions SERVICE_ROLE (VITE_ vars ship to the browser)", () => {
    for (const [path, content] of Object.entries(TEMPLATE_FILES)) {
      const names = content.match(/VITE_[A-Z0-9_]+/g) ?? [];
      for (const n of names) expect(n, `${path}: ${n}`).not.toMatch(/SERVICE/);
    }
  });

  it("no app file mentions service_role (SQL and CLAUDE.md may name the role)", () => {
    for (const [path, content] of Object.entries(TEMPLATE_FILES)) {
      if (path === STARTER_SQL_PATH || path === "CLAUDE.md") continue;
      expect(content.toLowerCase(), path).not.toContain("service_role");
    }
  });

  it(".env.example has empty values only", () => {
    for (const line of TEMPLATE_FILES[".env.example"].split("\n")) {
      const t = line.trim();
      if (!t || t.startsWith("#")) continue;
      expect(t).toMatch(/^VITE_SUPABASE_(URL|ANON_KEY)=$/);
    }
  });

  it("the supabase client reads only the two public VITE_ vars and shows a not-configured notice", () => {
    const client = TEMPLATE_FILES["src/lib/supabase.ts"];
    expect(client).toContain("import.meta.env.VITE_SUPABASE_URL");
    expect(client).toContain("import.meta.env.VITE_SUPABASE_ANON_KEY");
    expect(TEMPLATE_FILES["src/components/NotConfigured.tsx"]).toMatch(/not configured/i);
  });
});

describe("vite-react-supabase starter: starter.sql security", () => {
  it("enables RLS on profiles", () => {
    expect(sqlBody()).toMatch(/alter table public\.profiles enable row level security/i);
  });

  it("profiles.role is constrained", () => {
    expect(sqlBody()).toMatch(/role\s+text\s+not null\s+default 'member'\s+check \(role in \('member', 'admin'\)\)/i);
  });

  it("is_admin() is security definer with an empty search_path and fully qualified names", () => {
    const body = sqlBody();
    const fn = body.match(/create or replace function public\.is_admin\(\)[\s\S]*?\$\$;/i)?.[0] ?? "";
    expect(fn).not.toBe("");
    expect(fn).toMatch(/security definer/i);
    expect(fn).toMatch(/set search_path = ''/i);
    expect(fn).toMatch(/from public\.profiles/i);
    expect(fn).toMatch(/auth\.uid\(\)/i);
  });

  it("revokes is_admin() from public and grants only authenticated", () => {
    const body = sqlBody();
    expect(body).toMatch(/revoke all on function public\.is_admin\(\) from public/i);
    expect(body).toMatch(/revoke all on function public\.is_admin\(\) from anon/i);
    expect(body).toMatch(/grant execute on function public\.is_admin\(\) to authenticated/i);
  });

  it("every security definer function pins an empty search_path", () => {
    const fns = sqlBody().match(/create or replace function[\s\S]*?\$\$;/gi) ?? [];
    expect(fns.length).toBeGreaterThanOrEqual(2);
    for (const fn of fns) {
      if (/security definer/i.test(fn)) expect(fn).toMatch(/set search_path = ''/i);
    }
  });

  it("the signup trigger always inserts role 'member' (no first-user-is-admin)", () => {
    const body = sqlBody();
    const fn = body.match(/create or replace function public\.handle_new_user\(\)[\s\S]*?\$\$;/i)?.[0] ?? "";
    expect(fn).toMatch(/'member'/);
    expect(fn).not.toMatch(/'admin'/);
    expect(fn).not.toMatch(/count\s*\(/i);
    expect(body).not.toMatch(/first user/i);
    expect(body).toMatch(/after insert on auth\.users/i);
  });

  it("a signed-in user cannot change their own role", () => {
    const body = sqlBody();
    expect(body).not.toMatch(/create policy[^;]*for (insert|update|all)[^;]*to authenticated/i);
    expect(body).toMatch(/revoke (insert, update, delete|all) on (table )?public\.profiles from anon, authenticated/i);
  });

  it("profiles policies let a user read their own row and admins read all", () => {
    const body = sqlBody();
    expect(body).toMatch(/for select\s+to authenticated\s+using \(id = \(select auth\.uid\(\)\) or public\.is_admin\(\)\)/i);
  });
});

