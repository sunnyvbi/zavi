describe("viteStarterProvider (SiteStarterProvider)", () => {
  it("returns the file map plus the starter SQL and manifest", () => {
    const withLock = { ...TEMPLATE_FILES, "package-lock.json": "{}" };
    const out = createViteStarterProvider(withLock).starterFiles();
    expect(out.files).toEqual(withLock);
    expect(out.starter_sql).toBe(TEMPLATE_FILES[STARTER_SQL_PATH]);
    expect(out.manifest_json).toBe(TEMPLATE_FILES[SITE_MANIFEST_PATH]);
  });

  it("returns a copy, so a caller cannot mutate the embedded map", () => {
    const withLock = { ...TEMPLATE_FILES, "package-lock.json": "{}" };
    const out = createViteStarterProvider(withLock).starterFiles();
    out.files["package.json"] = "tampered";
    expect(createViteStarterProvider(withLock).starterFiles().files["package.json"]).toBe(TEMPLATE_FILES["package.json"]);
  });

  it("refuses to seed a repo without a lockfile (the build would resolve names live from the registry)", () => {
    const { ["package-lock.json"]: _drop, ...noLock } = { ...TEMPLATE_FILES, "package-lock.json": "{}" };
    expect(() => createViteStarterProvider(noLock).starterFiles()).toThrow(VITE_STARTER_LOCKFILE_SCRIPT);
  });

  it("the default provider matches the lockfile state on disk", () => {
    if (HAS_LOCK) expect(viteStarterProvider.starterFiles().files["package-lock.json"]).toBeDefined();
    else expect(() => viteStarterProvider.starterFiles()).toThrow(VITE_STARTER_LOCKFILE_SCRIPT);
  });
});

