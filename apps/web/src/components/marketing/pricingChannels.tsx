const COMING_SOON = /\s*[-–—(]?\s*coming soon\s*\)?\s*$/i;

export type ChannelLine = {
  label: string;
  comingSoon: boolean;
  mark: Mark | null;
  heading: boolean;
};

export function readChannelLine(line: string): ChannelLine {
  if (line.trimEnd().endsWith(":")) {
    return { label: line, comingSoon: false, mark: null, heading: true };
  }
  const comingSoon = COMING_SOON.test(line);
  const label = comingSoon ? line.replace(COMING_SOON, "") : line;
  const key = label.toLowerCase().replace(/[–—]/g, "-").replace(/\s+/g, " ").trim();
  const hit = CHANNELS.find((c) => key === c.match || key.startsWith(`${c.match} `));
  return { label, comingSoon, mark: hit ? MARKS[hit.mark] : null, heading: false };
}

