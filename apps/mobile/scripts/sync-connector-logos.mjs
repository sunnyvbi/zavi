import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "../../web");
const map = readFileSync(join(web, "src/components/workspace/settings/connectorLogos.ts"), "utf8");

const files = { SLACK_ICON: map.match(/SLACK_ICON\s*=\s*"([^"]+)"/)[1] };
const block = map.slice(map.indexOf("export const CONNECTOR_ICON"));
const entries = [];
for (const m of block.matchAll(/^\s*([a-z_]+):\s*(SLACK_ICON|"([^"]+)")/gm)) {
  entries.push([m[1], m[3] ?? files[m[2]]]);
}

const xml = (path) =>
  readFileSync(join(web, "public", path), "utf8")
    .replace(/<\?xml[^>]*>/, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+/g, " ")
    .trim();

let out =
  "// GENERATED by scripts/sync-connector-logos.mjs from the web's connector logos. Do not edit.\n" +
  "export const CONNECTOR_LOGO_XML: Readonly<Record<string, string>> = {\n";
for (const [slug, path] of entries) out += `  ${slug}: ${JSON.stringify(xml(path))},\n`;
out += "};\n";
writeFileSync(join(here, "../src/components/connections/connectorLogos.generated.ts"), out);
console.log(`wrote ${entries.length} logos`);
